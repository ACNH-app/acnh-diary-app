function frequencyLabel(weight: number) {
  if (weight >= 70) return '매우 흔함';
  if (weight >= 40) return '흔함';
  if (weight >= 15) return '보통';
  if (weight >= 5) return '드묾';
  return '매우 희귀';
}

export function getBugAppearanceFrequency(
  item: Pick<EncyclopediaItem, 'category' | 'number'>,
  month: number,
) {
  if (item.category !== 'bugs' || item.number == null) return null;

  const weights = BUG_SPAWN_WEIGHTS_BY_NUMBER[item.number];
  if (!weights) return null;

  const currentWeight = weights[month];
  if (currentWeight != null) return frequencyLabel(currentWeight);

  const allWeights = Object.values(weights).filter((weight): weight is number => weight != null);
  if (allWeights.length === 0) return '조건 기반 출현';

  return `출현 기간 외 · ${frequencyLabel(Math.max(...allWeights))}`;
}
